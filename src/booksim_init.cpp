#include <fstream>
#include <iostream>
#include <string>

#include "booksim.hpp"
#include "booksim_init.hpp"
#include "config_utils.hpp"
#include "globals.hpp"
#include "routefunc.hpp"

void BooksimGlobalInit( const Configuration & config )
{
  /*initialize routing, traffic, injection functions
   */
  InitializeRoutingMap( config );

  gPrintActivity = (config.GetInt("print_activity") > 0);
  gTrace = (config.GetInt("viewer_trace") > 0);

  string watch_out_file = config.GetStr( "watch_out" );
  if(watch_out_file == "") {
    gWatchOut = NULL;
  } else if(watch_out_file == "-") {
    gWatchOut = &cout;
  } else {
    gWatchOut = new ofstream(watch_out_file.c_str());
  }
}

void BooksimGlobalCleanup( )
{
  /* ~TrafficManager already deletes gWatchOut when it is a real file stream,
   * but does not null it. Leaving a dangling pointer here is fatal for any
   * second Engine in the same process, so clear it unconditionally.
   */
  gWatchOut = NULL;
}
