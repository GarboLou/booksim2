#!/usr/bin/env python3
"""Two-socket dual-tree topologies: each socket's root complex (RC) heads a
PCIe tree of switches with 4 GPUs; the two RCs are joined by UPI, and
optionally the two top switches by an NTB. With 4 switches, --mesh also joins
the two lower switches by an NTB, so the switches form a 2x2 mesh whose two
horizontal links both cross sockets.

  utils/gen_dual_socket.py --switches 4 --placement A [--ntb | --mesh] -o DIR
  utils/gen_dual_socket.py --switches 2 [--ntb] -o DIR        (placement C)
  ... [--gen 4 --width 8]      every PCIe link at Gen4 x8 (default: full rate)
  ... [--gen 4 --width 8 --fabric-width 16]   GPU ports x8, the rest x16
  utils/gen_dual_socket.py --switches 4 --gpu-switches 0,0,2,2,1,1,3,3 ...
                               any placement: the switch of G0..G7 in order

Writes DIR/<name>.txt (pcinet topology) and DIR/<name>.cfg (base config in
the runfiles/simai_*.cfg format; apply utils/vc0_config.py for the VC0
switch model). Run from the booksim2 root: network_file is written relative
to it when DIR is inside it.

Routers: SW0 = 0 and SW1 = 1 are the top switches of sockets 0 and 1; with
4 switches, SW2 = 2 hangs under SW0 and SW3 = 3 under SW1. RC0 and RC1 come
next. Placement (GPUs G0-G3 in socket 0, G4-G7 in socket 1):
  A  4 switches: all 4 GPUs on the lower switch (SW2 / SW3)
  B  4 switches: 2 on the top switch, 2 on the lower switch
  C  2 switches: all 4 GPUs on the top switch (the only option)
--gpu-switches replaces the named placement with any assignment of G0..G7 to
switches (SW0 = 0 ... SW3 = 3); GPUs need not split 4 + 4 between sockets.
0,0,2,2,1,1,3,3 is B and 2,2,2,2,3,3,3,3 is A, apart from the header line.

--gen/--width set every PCIe link (GPU ports, root ports, switch-to-switch
links and NTBs) to that generation and lane count; without them PCIe links run
at the reference full rate, 1 flit/cycle = 64 GB/s (about Gen5 x16).
--fabric-width gives root ports, switch-to-switch links and NTBs their own lane
count (same generation); GPU ports and node 8 keep --width. UPI is
modelled first-order: one link with its own bandwidth (cycles per flit, 1 = 64
GB/s, independent of --gen/--width) and latency, under the same credit model
as PCIe; no UPI protocol or coherence traffic. The RC is a switch node; its peer-to-peer
forwarding limits are not modelled. All latencies and the UPI bandwidth are
placeholders (TODO calibrate).
"""

import argparse
import os
import sys

BASE_CFG = """// Two-socket dual-tree ({desc}). Generated by utils/gen_dual_socket.py.
// UPI and root-complex parameters are placeholders (TODO calibrate).
topology            = pcinet;
network_file        = {topo};
routing_function    = min;
sim_type            = flow;

num_vcs             = 4;
vc_buf_size         = 32;
output_buffer_size  = 4;             // must be finite whenever any link is derated

// Unit system: 1 flit = 64 B, 1 cycle = 1 ns, so Gen5 x16 == 1 flit/cycle.
flit_bytes              = 64;
pcie_mps                = 256;       // TODO calibrate from lspci -vv
pcie_tlp_overhead_bytes = 24;        // header + sequence + LCRC + framing
max_queued_packets      = 8;

credit_delay     = 2;
routing_delay    = 0;
vc_alloc_delay   = 1;
sw_alloc_delay   = 1;
st_final_delay   = 1;
vc_allocator     = islip;
sw_allocator     = islip;
alloc_iters      = 2;
"""


def fabric_note(args):
    """', fabric x16' when the fabric links differ from the GPU ports."""
    return ", fabric x%d" % args.fabric_width if args.fabric_width != args.width else ""


def build(args):
    if args.gpu_switches is not None:
        placement = "custom (G0..G7 on switches %s)" % ",".join(map(str, args.gpu_switches))
    elif args.switches == 2:
        placement = "C"
    else:
        placement = args.placement
        if placement not in ("A", "B"):
            sys.exit("gen_dual_socket: 4 switches take placement A or B")
    n_sw = args.switches
    rc0, rc1 = n_sw, n_sw + 1
    pcie = " gen %d width %d" % (args.gen, args.width) if args.gen else ""
    # Root ports, switch-to-switch links and NTBs; GPU ports and node 8 use pcie.
    fabric = " gen %d width %d" % (args.gen, args.fabric_width) if args.gen else ""
    ntbs = ("" if not args.ntb else ", NTBs SW0-SW1 and SW2-SW3 (mesh)" if args.mesh
            else ", NTB between SW0 and SW1")
    lines = ["# Two-socket dual-tree, %d switches, placement %s%s; UPI cpf %d lat %d%s"
             % (n_sw, placement, ntbs, args.upi_cpf, args.upi_lat,
                "; PCIe links gen %d x%d%s" % (args.gen, args.width, fabric_note(args))
                if args.gen else ""),
             "# Generated by utils/gen_dual_socket.py -- regenerate instead of editing.",
             "router 0 domain 0", "router 1 domain 1"]
    if n_sw == 4:
        lines += ["router 2 domain 0", "router 3 domain 1"]
    lines += ["router %d domain 0" % rc0, "router %d domain 1" % rc1]

    if args.gpu_switches is not None:
        gpus = {}
        for g, sw in enumerate(args.gpu_switches):
            gpus.setdefault(sw, []).append(g)
    elif placement == "A":
        gpus = {2: [0, 1, 2, 3], 3: [4, 5, 6, 7]}
    elif placement == "B":
        gpus = {0: [0, 1], 2: [2, 3], 1: [4, 5], 3: [6, 7]}
    else:
        gpus = {0: [0, 1, 2, 3], 1: [4, 5, 6, 7]}
    lines.append("# GPUs")
    for sw in sorted(gpus):
        for g in gpus[sw]:
            lines.append("router %d node %d lat 1%s" % (sw, g, pcie))

    lines.append("# Root ports: each top switch's upstream link to its socket's RC")
    lines.append("router %d router 0 link_type transparent lat %d%s" % (rc0, args.rc_lat, fabric))
    lines.append("router %d router 1 link_type transparent lat %d%s" % (rc1, args.rc_lat, fabric))
    if n_sw == 4:
        lines.append("# Lower switches under the top switches")
        lines.append("router 0 router 2 link_type transparent lat 2%s" % fabric)
        lines.append("router 1 router 3 link_type transparent lat 2%s" % fabric)
    lines.append("# UPI between the two sockets (first-order: bandwidth, latency, credits)")
    lines.append("router %d router %d link_type transparent lat %d cpf %d"
                 % (rc0, rc1, args.upi_lat, args.upi_cpf))
    if args.ntb:
        lines.append("# NTB between the two top switches (crosses sockets)")
        lines.append("router 0 router 1 port_type ntb link_type nontransparent lat %d%s"
                     % (args.ntb_lat, fabric))
    if args.mesh:
        lines.append("# NTB between the two lower switches (crosses sockets; 2x2 mesh)")
        lines.append("router 2 router 3 port_type ntb link_type nontransparent lat %d%s"
                     % (args.ntb_lat, fabric))
    lines.append("# Node 8: inert NVSwitch placeholder required by SimCCL (carries no traffic)")
    lines.append("router %d node 8 lat 1%s" % (rc0, pcie))
    return placement, "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--switches", type=int, choices=[2, 4], required=True)
    ap.add_argument("--placement", choices=["A", "B"], default=None,
                    help="4 switches only: A (default) or B")
    ap.add_argument("--gpu-switches", metavar="S0,...,S7",
                    help="switch of each GPU G0..G7 (0..switches-1), replacing --placement")
    ap.add_argument("--ntb", action="store_true", help="add the SW0-SW1 NTB link")
    ap.add_argument("--mesh", action="store_true",
                    help="4 switches only: NTBs SW0-SW1 and SW2-SW3 (implies --ntb)")
    ap.add_argument("--gen", type=int, choices=[1, 2, 3, 4, 5, 6],
                    help="PCIe generation of every PCIe link (needs --width)")
    ap.add_argument("--width", type=int, choices=[1, 2, 4, 8, 16],
                    help="PCIe lane count of every PCIe link (needs --gen)")
    ap.add_argument("--fabric-width", type=int, choices=[1, 2, 4, 8, 16],
                    help="lane count of root ports, switch-to-switch links and NTBs "
                         "(default --width; needs --gen and --width)")
    ap.add_argument("--upi-cpf", type=int, default=1,
                    help="UPI cycles per flit: 1 = 64 GB/s, 2 = 32, 4 = 16 (placeholder)")
    ap.add_argument("--upi-lat", type=int, default=20, help="UPI latency, ns (placeholder)")
    ap.add_argument("--rc-lat", type=int, default=2, help="root-port link latency, ns")
    ap.add_argument("--ntb-lat", type=int, default=5, help="NTB link latency, ns")
    ap.add_argument("-o", "--out", required=True, help="output directory")
    ap.add_argument("--name", help="file stem (default derived from the options)")
    args = ap.parse_args()
    if args.upi_cpf < 1:
        ap.error("--upi-cpf must be at least 1 (1 = 64 GB/s)")
    for opt in ("upi_lat", "rc_lat", "ntb_lat"):
        if getattr(args, opt) < 1:
            ap.error("--%s must be at least 1 ns (channel latencies are positive)"
                     % opt.replace("_", "-"))
    if args.gpu_switches is not None:
        if args.placement is not None:
            ap.error("--gpu-switches replaces --placement; give one of them")
        try:
            args.gpu_switches = [int(x) for x in args.gpu_switches.split(",")]
        except ValueError:
            ap.error("--gpu-switches takes 8 comma-separated switch numbers")
        if len(args.gpu_switches) != 8 or not all(0 <= x < args.switches for x in args.gpu_switches):
            ap.error("--gpu-switches takes 8 switch numbers, each 0..%d" % (args.switches - 1))
    if args.switches == 2 and args.placement is not None:
        ap.error("--placement applies to 4 switches only; 2 switches use placement C")
    if args.switches == 4 and args.placement is None and args.gpu_switches is None:
        args.placement = "A"
    if args.mesh and args.switches != 4:
        ap.error("--mesh needs --switches 4 (it joins the lower switches SW2 and SW3)")
    args.ntb = args.ntb or args.mesh
    if (args.gen is None) != (args.width is None):
        ap.error("--gen and --width go together")
    if args.fabric_width is not None and args.gen is None:
        ap.error("--fabric-width needs --gen and --width")
    if args.fabric_width is None:
        args.fabric_width = args.width

    placement, topo = build(args)
    name = args.name or "%s%d%s%s_u%d%s" % (
        "mesh" if args.mesh else "dt", args.switches,
        "P" + "".join(map(str, args.gpu_switches)) if args.gpu_switches is not None else placement,
        "_ntb" if args.ntb and not args.mesh else "", 64 // args.upi_cpf,
        "_g%dx%d%s" % (args.gen, args.width, "f%d" % args.fabric_width
                        if args.fabric_width != args.width else "") if args.gen else "")
    os.makedirs(args.out, exist_ok=True)
    topo_path = os.path.join(args.out, name + ".txt")
    with open(topo_path, "w") as f:
        f.write(topo)
    rel = os.path.relpath(os.path.abspath(topo_path), os.getcwd())
    desc = "%d switches, placement %s%s%s" % (
        args.switches, placement, ", 2x2 mesh (two NTBs)" if args.mesh else ", NTB" if args.ntb else "",
        ", PCIe gen %d x%d%s" % (args.gen, args.width, fabric_note(args)) if args.gen else "")
    with open(os.path.join(args.out, name + ".cfg"), "w") as f:
        f.write(BASE_CFG.format(desc=desc, topo=rel if not rel.startswith("..") else topo_path))
    print(name)
    return 0


if __name__ == "__main__":
    sys.exit(main())
