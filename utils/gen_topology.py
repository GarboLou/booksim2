#!/usr/bin/env python3
"""Generate PCINet topology + matching booksim config files parametrically.

PCINet's adjacency-list grammar (see src/networks/pcinet.cpp) is already
fully general -- arbitrary switches, GPUs, NTB-tagged links, no built-in
port-count cap. This generator turns a small parameter set (switch count,
GPUs per switch, a switch-interconnect family, which links are NTB, a port
budget) into a valid instance of that grammar, generalizing the five
hand-authored examples in runfiles/pcie_simai_*.txt to variable switch/GPU
counts. The port budget (a switch's total radix = GPU ports + inter-switch
ports) is enforced here, before any file is written -- BookSim itself never
caps a switch's radix.

Grammar clauses emitted (see src/networks/pcinet.cpp's header comment):
    router <r> node <n> [port_type ...] [domain <d>] [lat <l>] [gen <g> width <w> | bw_gbps <f> | cpf <n>]
    router <r> router <r2> [port_type ...] [link_type ...] [lat <l>] [gen/width|bw_gbps|cpf]
    router <r> domain <d>
"""

import argparse
import itertools
import json
import math
import os
import sys

CFG_TEMPLATE = """\
// Generated by utils/gen_topology.py -- do not hand-edit, regenerate instead.
topology            = pcinet;
network_file        = {network_file};
routing_function    = min;
sim_type            = flow;          // externally driven: the frontend owns the clock

num_vcs             = 4;
vc_buf_size         = 32;
output_buffer_size  = 4;             // must be finite whenever any link is derated

// Unit system: 1 flit = 64 B, 1 cycle = 1 ns.
flit_bytes              = 64;
pcie_mps                = 256;       // TODO calibrate from lspci -vv
pcie_tlp_overhead_bytes = 24;        // header + sequence + LCRC + framing
max_queued_packets      = 8;

credit_delay     = 2;
routing_delay    = 0;
vc_alloc_delay   = 1;
sw_alloc_delay   = 1;
st_final_delay   = 1;
vc_allocator     = islip;
sw_allocator     = islip;
alloc_iters      = 2;
"""

NODE_GEN = 5
NODE_WIDTH = 16


class TopologyModel:
    """In-memory model: switches, their GPU counts/domain, and inter-switch
    edges. Shared representation between the family builders, the .txt/.cfg
    emitters, and (as a library import) the sweep driver / placement search."""

    def __init__(self, num_switches):
        self.num_switches = num_switches
        self.gpu_count = [0] * num_switches       # per switch
        self.domain = [0] * num_switches           # per switch
        self.edges = []                            # list of (u, v, attrs dict)

    def add_edge(self, u, v, port_type, link_type, lat, bw):
        self.edges.append((u, v, {
            "port_type": port_type, "link_type": link_type, "lat": lat, "bw": bw,
        }))

    def inter_switch_degree(self):
        deg = [0] * self.num_switches
        for u, v, _ in self.edges:
            deg[u] += 1
            deg[v] += 1
        return deg

    def node_ranges(self):
        """switch index -> range(first_gpu_node_id, first_gpu_node_id + count)"""
        ranges = []
        nxt = 0
        for s in range(self.num_switches):
            ranges.append(range(nxt, nxt + self.gpu_count[s]))
            nxt += self.gpu_count[s]
        return ranges

    def total_gpus(self):
        return sum(self.gpu_count)

    def placeholder_node(self):
        return self.total_gpus()


def _bw_clause(bw):
    """bw is one of ('cpf', n), ('bw_gbps', f), ('gen', g, w). Returns the
    trailing clause tokens as a string, honoring PCINet's precedence
    (explicit cpf > bw_gbps > gen+width > default)."""
    kind = bw[0]
    if kind == "cpf":
        return "cpf %d" % bw[1]
    if kind == "bw_gbps":
        return "bw_gbps %s" % bw[1]
    if kind == "gen":
        return "gen %d width %d" % (bw[1], bw[2])
    raise ValueError("bad bw spec %r" % (bw,))


def _parse_bw_spec(args):
    if args.link_cpf is not None:
        return ("cpf", args.link_cpf)
    if args.link_bw_gbps is not None:
        return ("bw_gbps", args.link_bw_gbps)
    return ("gen", args.link_gen, args.link_width)


def _parse_gpus_per_switch(spec, count):
    """spec is an int, or a comma list of ints. Returns a list of length
    `count` (broadcasting a scalar)."""
    if isinstance(spec, int):
        return [spec] * count
    vals = [int(x) for x in str(spec).split(",")]
    if len(vals) == 1:
        return vals * count
    if len(vals) != count:
        sys.exit("--gpus-per-switch: expected 1 or %d values, got %d" % (count, len(vals)))
    return vals


def _parse_ntb_spec(spec, edges_uv):
    """spec is 'none', 'all', 'root-root' (caller resolves which edges that
    means), or a comma list of 'u-v' pairs. Returns a set of (u, v) pairs
    (as given, i.e. not order-normalized -- callers compare both orders)."""
    if spec in (None, "none"):
        return set()
    if spec == "all":
        return set((u, v) for u, v in edges_uv)
    if spec == "root-root":
        return "root-root"  # resolved by the tree family builder
    pairs = set()
    for tok in spec.split(","):
        u, v = tok.split("-")
        pairs.add((int(u), int(v)))
    return pairs


def _is_ntb(ntb_set, u, v):
    if ntb_set == "root-root":
        return False  # resolved earlier and replaced with a concrete set
    return (u, v) in ntb_set or (v, u) in ntb_set


# ---------------------------------------------------------------------------
# Family builders. Each returns a fully-populated TopologyModel.
# ---------------------------------------------------------------------------

def build_flat(args):
    if args.switches != 1:
        sys.exit("family=flat requires --switches 1")
    m = TopologyModel(1)
    m.gpu_count = _parse_gpus_per_switch(args.gpus_per_switch, 1)
    m.domain = [0]
    return m


def _grid_dims(switches, grid_arg, default_shape):
    if grid_arg:
        rows, cols = (int(x) for x in grid_arg.lower().split("x"))
        if rows * cols != switches:
            sys.exit("--grid %s doesn't multiply to --switches %d" % (grid_arg, switches))
        return rows, cols
    if default_shape == "ring":
        # ring_torus's default meaning is a literal ring of switches, not a
        # square torus -- that's what runfiles/pcie_simai_ring_torus.txt is,
        # and it's a genuinely different topology from a 2x2 (or larger)
        # square torus. Pass --grid explicitly to get a true multi-dimensional
        # torus instead.
        return 1, switches
    # mesh_grid: closest-to-square factorization
    best = (1, switches)
    for r in range(1, int(math.isqrt(switches)) + 1):
        if switches % r == 0:
            best = (r, switches // r)
    return best


def build_grid(args, torus):
    rows, cols = _grid_dims(args.switches, args.grid, "ring" if torus else "square")
    S = rows * cols
    m = TopologyModel(S)
    m.gpu_count = _parse_gpus_per_switch(args.gpus_per_switch, S)
    m.domain = [0] * S

    def idx(r, c):
        return r * cols + c

    raw_edges = []
    for r in range(rows):
        for c in range(cols):
            if c + 1 < cols:
                raw_edges.append((idx(r, c), idx(r, c + 1)))
            elif torus and cols > 2:
                raw_edges.append((idx(r, c), idx(r, 0)))
            if r + 1 < rows:
                raw_edges.append((idx(r, c), idx(r + 1, c)))
            elif torus and rows > 2:
                raw_edges.append((idx(r, c), idx(0, c)))
    # de-dup (a 1xN or Nx1 grid with torus=True is a plain ring; the two loops
    # above would otherwise emit the wraparound edge twice for a 1-row/1-col
    # grid since both the "row" and "col" wraparound branches fire)
    raw_edges = sorted(set(tuple(sorted(e)) for e in raw_edges))

    bw = _parse_bw_spec(args)
    ntb_set = _parse_ntb_spec(args.ntb, raw_edges)
    if ntb_set == "root-root":
        sys.exit("--ntb root-root only applies to family=dual_tree/ntb_tree")
    for u, v in raw_edges:
        ntb = _is_ntb(ntb_set, u, v)
        if ntb:
            m.add_edge(u, v, "ntb", "nontransparent", args.ntb_lat, bw)
        else:
            m.add_edge(u, v, "generic", "transparent", args.link_lat, bw)
    return m


def build_full_mesh(args):
    S = args.switches
    m = TopologyModel(S)
    m.gpu_count = _parse_gpus_per_switch(args.gpus_per_switch, S)
    m.domain = [0] * S
    raw_edges = list(itertools.combinations(range(S), 2))
    bw = _parse_bw_spec(args)
    ntb_set = _parse_ntb_spec(args.ntb, raw_edges)
    if ntb_set == "root-root":
        sys.exit("--ntb root-root only applies to family=dual_tree/ntb_tree")
    for u, v in raw_edges:
        if _is_ntb(ntb_set, u, v):
            m.add_edge(u, v, "ntb", "nontransparent", args.ntb_lat, bw)
        else:
            m.add_edge(u, v, "generic", "transparent", args.link_lat, bw)
    return m


def build_tree(args, ntb_default):
    D = args.domains
    S = args.switches
    if S <= D:
        sys.exit("family=dual_tree/ntb_tree needs --switches > --domains")
    if (S - D) % D != 0:
        sys.exit("family=dual_tree/ntb_tree needs (--switches - --domains) divisible "
                  "by --domains (%d leaves don't split evenly across %d roots)" % (S - D, D))
    leaves_per_root = (S - D) // D
    m = TopologyModel(S)
    # switches 0..D-1 are roots, D..S-1 are leaves, grouped by root
    leaf_gpus = _parse_gpus_per_switch(args.gpus_per_switch, S - D)
    m.gpu_count = [0] * D + leaf_gpus
    m.domain = list(range(D)) + [r for r in range(D) for _ in range(leaves_per_root)]

    bw = _parse_bw_spec(args)
    root_leaf_pt = "downstream"
    # root-leaf uplinks: always transparent, never NTB (matches the reference examples)
    for root in range(D):
        for k in range(leaves_per_root):
            leaf = D + root * leaves_per_root + k
            m.add_edge(root, leaf, root_leaf_pt, "transparent", args.link_lat, bw)

    # roots chained root_i -- root_{i+1}
    root_edges = [(i, i + 1) for i in range(D - 1)]
    ntb_spec = args.ntb if args.ntb is not None else ntb_default
    ntb_set = _parse_ntb_spec(ntb_spec, root_edges)
    if ntb_set == "root-root":
        ntb_set = set(root_edges)
    elif ntb_spec == "all":
        ntb_set = set(root_edges)  # "all" among roots (leaves never get NTB)
    for u, v in root_edges:
        if _is_ntb(ntb_set, u, v):
            m.add_edge(u, v, "ntb", "nontransparent", args.ntb_lat, bw)
        else:
            m.add_edge(u, v, root_leaf_pt, "transparent", args.link_lat, bw)
    return m


def build_custom(args):
    if not args.custom_graph:
        sys.exit("family=custom requires --custom-graph FILE")
    with open(args.custom_graph) as f:
        spec = json.load(f)
    switches = spec["switches"]
    S = len(switches)
    m = TopologyModel(S)
    m.gpu_count = [sw.get("gpus", 0) for sw in switches]
    m.domain = [sw.get("domain", 0) for sw in switches]
    default_bw = _parse_bw_spec(args)
    for e in spec["edges"]:
        u, v = e["u"], e["v"]
        ntb = e.get("ntb", False)
        lat = e.get("lat", args.ntb_lat if ntb else args.link_lat)
        port_type = e.get("port_type", "ntb" if ntb else "generic")
        link_type = e.get("link_type", "nontransparent" if ntb else "transparent")
        bw = ("gen", e["gen"], e["width"]) if "gen" in e else \
             (("bw_gbps", e["bw_gbps"]) if "bw_gbps" in e else
              (("cpf", e["cpf"]) if "cpf" in e else default_bw))
        m.add_edge(u, v, port_type, link_type, lat, bw)
    return m


FAMILIES = {
    "flat": build_flat,
    "mesh_grid": lambda a: build_grid(a, torus=False),
    "ring_torus": lambda a: build_grid(a, torus=True),
    "full_mesh": build_full_mesh,
    "dual_tree": lambda a: build_tree(a, ntb_default="none"),
    "ntb_tree": lambda a: build_tree(a, ntb_default="root-root"),
    "custom": build_custom,
}


def check_radix(model, radix_budget):
    deg = model.inter_switch_degree()
    problems = []
    for s in range(model.num_switches):
        radix = model.gpu_count[s] + deg[s]
        if radix > radix_budget:
            problems.append((s, model.gpu_count[s], deg[s], radix))
    return problems


def build_topology(args):
    if args.family not in FAMILIES:
        sys.exit("unknown family %r" % args.family)
    model = FAMILIES[args.family](args)
    problems = check_radix(model, args.switch_radix)
    if problems:
        lines = ["switch %d: %d GPU + %d inter-switch = %d > radix budget %d"
                  % (s, g, d, r, args.switch_radix) for s, g, d, r in problems]
        sys.exit("gen_topology: port budget exceeded:\n  " + "\n  ".join(lines))
    return model


# ---------------------------------------------------------------------------
# Emission
# ---------------------------------------------------------------------------

def emit_topology_text(model, node_lat):
    lines = []
    ranges = model.node_ranges()

    for s in range(model.num_switches):
        if model.gpu_count[s] == 0:
            lines.append("router %d domain %d" % (s, model.domain[s]))
        for n in ranges[s]:
            lines.append("router %d domain %d node %d port_type downstream domain %d "
                          "lat %d gen %d width %d"
                          % (s, model.domain[s], n, model.domain[s], node_lat,
                             NODE_GEN, NODE_WIDTH))

    for u, v, attrs in model.edges:
        lines.append("router %d router %d port_type %s link_type %s lat %d %s"
                      % (u, v, attrs["port_type"], attrs["link_type"], attrs["lat"],
                         _bw_clause(attrs["bw"])))

    placeholder = model.placeholder_node()
    lines.append("# node %d: inert NVSwitch placeholder required by SimCCL "
                  "(see runfiles/pcie_simai_flat.txt)" % placeholder)
    lines.append("router 0 node %d lat 1 gen %d width %d" % (placeholder, NODE_GEN, NODE_WIDTH))

    return "\n".join(lines) + "\n"


def emit_cfg_text(network_file):
    return CFG_TEMPLATE.format(network_file=network_file)


def write_files(model, out_prefix, node_lat):
    txt_path = out_prefix + ".txt"
    cfg_path = out_prefix + ".cfg"
    os.makedirs(os.path.dirname(txt_path) or ".", exist_ok=True)
    with open(txt_path, "w") as f:
        f.write(emit_topology_text(model, node_lat))
    with open(cfg_path, "w") as f:
        f.write(emit_cfg_text(txt_path))
    return txt_path, cfg_path


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                  formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--family", required=True, choices=sorted(FAMILIES))
    ap.add_argument("--switches", type=int, default=1)
    ap.add_argument("--gpus-per-switch", default="1",
                    help="int, or comma list (one per switch for mesh/ring/full_mesh, "
                         "one per leaf for dual_tree/ntb_tree)")
    ap.add_argument("--switch-radix", type=int, default=64,
                    help="port budget per switch; hard error if any switch exceeds it")
    ap.add_argument("--ntb", default=None,
                    help="'none' (default), 'all', 'root-root' (tree families), or a "
                         "comma list of u-v switch-index pairs to mark NTB")
    ap.add_argument("--link-gen", type=int, default=5)
    ap.add_argument("--link-width", type=int, default=16)
    ap.add_argument("--link-bw-gbps", type=float, default=None)
    ap.add_argument("--link-cpf", type=int, default=None)
    ap.add_argument("--ntb-lat", type=int, default=5)
    ap.add_argument("--link-lat", type=int, default=2)
    ap.add_argument("--node-lat", type=int, default=1)
    ap.add_argument("--grid", default=None, help="RxC, mesh_grid/ring_torus only")
    ap.add_argument("--domains", type=int, default=2, help="number of root switches, tree families only")
    ap.add_argument("--custom-graph", default=None, help="JSON switch-adjacency file, family=custom only")
    ap.add_argument("--out-prefix", required=True)
    args = ap.parse_args()

    model = build_topology(args)
    txt_path, cfg_path = write_files(model, args.out_prefix, args.node_lat)
    sys.stderr.write("%s: %d switches, %d GPUs, %d inter-switch links -> %s, %s\n"
                      % (args.family, model.num_switches, model.total_gpus(),
                         len(model.edges), txt_path, cfg_path))


if __name__ == "__main__":
    main()
